// An order event becomes a one-page PDF invoice, written by hand: the page's
// content stream is deflate-compressed and the document ID is an MD5 hash.
import { createHash } from 'node:crypto';
import { deflateSync } from 'node:zlib';

// PDF strings escape backslashes and parentheses
const str = (s) => `(${String(s).replace(/[\\()]/g, (c) => `\\${c}`)})`;
const money = (n, currency) => `${Number(n).toFixed(2)} ${currency}`;

function pdf(objects) {
  let out = '%PDF-1.7\n%\xe2\xe3\xcf\xd3\n';
  const offsets = [];
  objects.forEach((body, i) => {
    offsets.push(Buffer.byteLength(out, 'latin1'));
    out += `${i + 1} 0 obj\n`;
    out += Buffer.isBuffer(body) ? body.toString('latin1') : body;
    out += '\nendobj\n';
  });
  const xref = Buffer.byteLength(out, 'latin1');
  const id = createHash('md5').update(out, 'latin1').digest('hex');
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R /ID [<${id}> <${id}>] >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

export default {
  transform(request) {
    const order = request.body;

    // Page content: text operators at absolute positions (origin bottom left, A4 is 595x842)
    const lines = [];
    const at = (x, y, size, font, s) => lines.push(`BT /${font} ${size} Tf ${x} ${y} Td ${str(s)} Tj ET`);
    lines.push('0.12 0.56 0.24 rg 0 806 595 36 re f 1 g');
    at(48, 816, 14, 'F2', 'INVOICE');
    at(420, 816, 10, 'F1', `Order ${order.name}`);
    lines.push('0 g');
    at(48, 760, 10, 'F1', 'Bill to');
    at(48, 744, 12, 'F2', order.customer.name);
    at(48, 729, 10, 'F1', order.customer.email);
    at(400, 760, 10, 'F1', 'Date');
    at(400, 744, 12, 'F2', order.created_at.slice(0, 10));

    let y = 680;
    at(48, y, 10, 'F2', 'Item');
    at(380, y, 10, 'F2', 'Qty');
    at(470, y, 10, 'F2', 'Amount');
    lines.push(`0.8 G 48 ${y - 8} m 547 ${y - 8} l S 0 G`);
    for (const item of order.line_items) {
      y -= 26;
      at(48, y, 11, 'F1', item.title);
      at(380, y, 11, 'F1', item.quantity);
      at(470, y, 11, 'F1', money(item.price * item.quantity, order.currency));
    }
    lines.push(`0.8 G 48 ${y - 12} m 547 ${y - 12} l S 0 G`);
    at(380, y - 34, 12, 'F2', 'Total');
    at(470, y - 34, 12, 'F2', money(order.total_price, order.currency));
    at(48, 60, 8, 'F1', `Generated by a Hookdeck transformation from ${order.admin_graphql_api_id}`);

    const content = deflateSync(Buffer.from(lines.join('\n'), 'latin1'));
    request.body = pdf([
      '<< /Type /Catalog /Pages 2 0 R >>',
      '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>',
      Buffer.concat([
        Buffer.from(`<< /Length ${content.length} /Filter /FlateDecode >>\nstream\n`),
        content,
        Buffer.from('\nendstream'),
      ]),
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    ]);
    request.headers['content-type'] = 'application/pdf';
    console.log(`Invoice for order ${order.name}: ${order.line_items.length} items, ${request.body.length} bytes`);
    return request;
  },
};
